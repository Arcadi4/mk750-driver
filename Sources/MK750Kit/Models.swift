import Foundation

// MARK: - Public value model

/// The eight state bytes of one lighting channel.
///
/// `flags` is the entire option/flags byte from byte 4 of the wire packet,
/// including the high option nibble. Keep it intact when round-tripping a
/// state read from the keyboard so a mode-specific option is not lost.
public struct LightState: Codable, Equatable, Sendable {
  /// Wire mode number, 1...31 on this protocol family.
  public var mode: UInt8
  /// Speed wire index (0...5 for yc500; 0 is fastest for most modes).
  public var speed: UInt8
  /// Brightness (0...4 on most boards).
  public var brightness: UInt8
  /// Entire flags/option byte: low nibble flags, high nibble mode option.
  public var flags: UInt8
  public var red: UInt8
  public var green: UInt8
  public var blue: UInt8

  public init(
    mode: UInt8,
    speed: UInt8,
    brightness: UInt8,
    flags: UInt8,
    red: UInt8,
    green: UInt8,
    blue: UInt8
  ) {
    self.mode = mode
    self.speed = speed
    self.brightness = brightness
    self.flags = flags
    self.red = red
    self.green = green
    self.blue = blue
  }
}

