// MARK: - Macro codec

/// One macro event plus the delay stored after it.
///
/// A key event uses a HID keyboard usage (`0x04...0xEF`), a mouse button uses
/// `0xF0...0xF4`, and `0xF9` is a mouse movement carrying `dx`/`dy`. Macro
/// blobs store exactly one event and its delay per step; the four zero byte
/// terminator is generated by `MacroSequence.encoded()`.
public struct MacroStep: Codable, Equatable, Sendable {
  public var code: UInt8
  public var pressed: Bool
  public var delay: UInt16
  public var dx: Int8
  public var dy: Int8

  public init(code: UInt8, pressed: Bool, delay: UInt16, dx: Int8 = 0, dy: Int8 = 0) {
    self.code = code
    self.pressed = pressed
    self.delay = delay
    self.dx = dx
    self.dy = dy
  }
}

/// A macro as an ordered event/delay stream plus its repeat count.
public struct MacroSequence: Codable, Equatable, Sendable {
  public static let blobLength = 256
  public static let headerLength = 2
  public static let terminatorLength = 4
  public static let maximumStreamLength = blobLength - headerLength - terminatorLength

  public var repeatCount: UInt16
  public var steps: [MacroStep]

  public init(repeatCount: UInt16, steps: [MacroStep]) {
    self.repeatCount = repeatCount
    self.steps = steps
  }

  /// Builds the exact 256-byte blob. Compact key events use
  /// `[code, pressed<<7 | delay]` for delays 1...127; delay 0 and delays
  /// above 127 use the four-byte `[code, pressed<<7, delay u16 LE]` form.
  /// Mouse moves use `[0xF9, delay, dx, dy]`.
  public func encoded() throws -> [UInt8] {
    var stream: [UInt8] = []
    stream.reserveCapacity(MacroSequence.maximumStreamLength)

    for step in steps {
      switch step.code {
      case 0xF9:
        guard !step.pressed else {
          throw MK750Error.macroEncoding("a mouse move cannot carry a pressed state")
        }
        guard step.delay <= UInt16(UInt8.max) else {
          throw MK750Error.macroEncoding("a mouse move delay exceeds 255 ms")
        }
        stream.append(0xF9)
        stream.append(UInt8(step.delay))
        stream.append(UInt8(bitPattern: step.dx))
        stream.append(UInt8(bitPattern: step.dy))

      case 0xF0...0xF4, 0x04...0xEF:
        guard step.dx == 0, step.dy == 0 else {
          throw MK750Error.macroEncoding("dx/dy are only valid for mouse-move events")
        }
        if step.delay > 0 && step.delay <= 127 {
          stream.append(step.code)
          stream.append((step.pressed ? 0x80 : 0x00) | UInt8(step.delay))
        } else {
          stream.append(step.code)
          stream.append(step.pressed ? 0x80 : 0x00)
          stream.append(UInt8(step.delay & 0x00FF))
          stream.append(UInt8(step.delay >> 8))
        }

      default:
        throw MK750Error.macroEncoding(
          String(format: "unsupported macro event code 0x%02X", step.code)
        )
      }
    }

    guard stream.count <= MacroSequence.maximumStreamLength else {
      throw MK750Error.macroEncoding(
        "macro needs \(stream.count) event bytes; the 256-byte blob leaves \(MacroSequence.maximumStreamLength)"
      )
    }

    var blob = [UInt8](repeating: 0, count: MacroSequence.blobLength)
    blob[0] = UInt8(repeatCount & 0x00FF)
    blob[1] = UInt8(repeatCount >> 8)
    blob.replaceSubrange(
      MacroSequence.headerLength..<(MacroSequence.headerLength + stream.count),
      with: stream
    )
    // The four zero bytes at the end of the event stream are the
    // terminator. The remaining blob bytes stay zero.
    return blob
  }

  /// Decodes a 256-byte blob. Rejects unknown codes, truncated events,
  /// a missing terminator, and non-zero bytes after the terminator so the
  /// UI can fall back to showing the raw bytes instead of inventing steps.
  public static func decode(_ bytes: [UInt8]) throws -> MacroSequence {
    guard bytes.count == blobLength else {
      throw MK750Error.macroEncoding(
        "macro blob must be \(blobLength) bytes, got \(bytes.count)"
      )
    }

    let repeatCount = UInt16(bytes[0]) | (UInt16(bytes[1]) << 8)
    var steps: [MacroStep] = []
    var cursor = headerLength

    while true {
      guard cursor + terminatorLength <= bytes.count else {
        throw MK750Error.macroEncoding("macro stream ends before a four-byte terminator")
      }
      if bytes[cursor] == 0,
        bytes[cursor + 1] == 0,
        bytes[cursor + 2] == 0,
        bytes[cursor + 3] == 0
      {
        let trailing = bytes[(cursor + terminatorLength)...]
        guard trailing.allSatisfy({ $0 == 0 }) else {
          throw MK750Error.macroEncoding("non-zero bytes follow the macro terminator")
        }
        return MacroSequence(repeatCount: repeatCount, steps: steps)
      }

      let code = bytes[cursor]
      switch code {
      case 0xF9:
        guard cursor + 4 <= bytes.count else {
          throw MK750Error.macroEncoding("truncated mouse-move event")
        }
        steps.append(
          MacroStep(
            code: code,
            pressed: false,
            delay: UInt16(bytes[cursor + 1]),
            dx: Int8(bitPattern: bytes[cursor + 2]),
            dy: Int8(bitPattern: bytes[cursor + 3])
          )
        )
        cursor += 4

      case 0xF0...0xF4, 0x04...0xEF:
        guard cursor + 2 <= bytes.count else {
          throw MK750Error.macroEncoding("truncated key event")
        }
        let flags = bytes[cursor + 1]
        let pressed = (flags & 0x80) != 0
        let compactDelay = flags & 0x7F
        if compactDelay != 0 {
          steps.append(
            MacroStep(code: code, pressed: pressed, delay: UInt16(compactDelay))
          )
          cursor += 2
        } else {
          guard cursor + 4 <= bytes.count else {
            throw MK750Error.macroEncoding("truncated extended-delay key event")
          }
          let delay = UInt16(bytes[cursor + 2]) | (UInt16(bytes[cursor + 3]) << 8)
          steps.append(MacroStep(code: code, pressed: pressed, delay: delay))
          cursor += 4
        }

      default:
        throw MK750Error.macroEncoding(
          String(format: "unsupported macro event code 0x%02X", code)
        )
      }
    }
  }
}

// MARK: - Errors

/// Actionable failures surfaced by `Keyboard`. Every case is safe to show to
/// the user; none implies a write succeeded.
public enum MK750Error: Error, Equatable, Sendable {
  /// No connection has been established, or a transport failure cleared it.
  case notConnected
  /// The vendor feature collection was not present in the current enumeration.
  case deviceNotFound
  /// Enumeration succeeded but the device did not answer as board 849 with a
  /// valid revision.
  case identityFailed(String)
  /// The device did not behave like the yc500 family this tool implements.
  case familyUnverified(String)
  /// A requested operation is outside the documented, safe subset.
  case unsupported(String)
  /// An argument failed validation before any packet was sent.
  case invalidArgument(String)
  /// The transport (IOKit or an injected test double) raised an error.
  case transport(String)
  /// A write was sent but read-back did not prove it landed.
  case verificationFailed(String)
  /// The mandatory on-disk backup could not be written, so nothing was sent.
  case backupFailed(String)
  /// A macro sequence cannot be represented in the 256-byte wire blob.
  case macroEncoding(String)
}

extension MK750Error: LocalizedError {
  public var errorDescription: String? {
    switch self {
    case .notConnected:
      return "The keyboard is not connected. Reconnect the USB-C cable and try again."
    case .deviceNotFound:
      return
        "No MK750 vendor collection (3151:4015, usage 0xFFFF:2) was found. Use a wired USB-C connection."
    case .identityFailed(let detail):
      return "The device did not identify as an MK750: \(detail)"
    case .familyUnverified(let detail):
      return
        "The keyboard's command family could not be verified, so writes are disabled: \(detail)"
    case .unsupported(let detail):
      return "This operation is outside the safely supported protocol subset: \(detail)"
    case .invalidArgument(let detail):
      return "Invalid request: \(detail)"
    case .transport(let detail):
      return "USB communication failed: \(detail). Replug the keyboard before retrying."
    case .verificationFailed(let detail):
      return "The keyboard did not confirm the change: \(detail)"
    case .backupFailed(let detail):
      return "The backup could not be saved, so nothing was written: \(detail)"
    case .macroEncoding(let detail):
      return "The macro cannot be encoded: \(detail)"
    }
  }
}
